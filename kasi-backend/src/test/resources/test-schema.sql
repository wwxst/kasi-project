-- H2测试表结构（与MySQL兼容）

CREATE TABLE IF NOT EXISTS short_drama_provider (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    provider_code VARCHAR(32) NOT NULL,
    provider_name VARCHAR(64) NOT NULL,
    status TINYINT NOT NULL DEFAULT 1,
    UNIQUE (provider_code)
);

CREATE TABLE IF NOT EXISTS short_drama_connection (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    provider_id BIGINT NOT NULL,
    connection_name VARCHAR(64) NOT NULL,
    base_url VARCHAR(512) DEFAULT NULL,
    media_root_domain VARCHAR(253) DEFAULT NULL,
    partner_id VARCHAR(64) DEFAULT NULL,
    api_key_ciphertext TEXT DEFAULT NULL,
    currency CHAR(3) NOT NULL,
    status TINYINT NOT NULL DEFAULT 1,
    filing_mode VARCHAR(16) NOT NULL DEFAULT 'API',
    created_by BIGINT DEFAULT NULL,
    updated_by BIGINT DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (provider_id));

MERGE INTO short_drama_provider (provider_code, provider_name, status)
KEY (provider_code) VALUES ('GOODSHORT', 'GoodShort', 1);

CREATE TABLE IF NOT EXISTS provider_commission_rule (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    provider_id BIGINT NOT NULL,
    channel_fee_rate DECIMAL(12, 10) NOT NULL,
    principal_fee_rate DECIMAL(12, 10) NOT NULL,
    principal_commission_rate DECIMAL(12, 10) NOT NULL,
    downstream_fee_rate DECIMAL(12, 10) NOT NULL,
    downstream_commission_rate DECIMAL(12, 10) NOT NULL,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (provider_id));

CREATE TABLE IF NOT EXISTS sys_admin_user (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password VARCHAR(255) NOT NULL,
    real_name VARCHAR(64) NOT NULL,
    mobile VARCHAR(32) DEFAULT NULL,
    email VARCHAR(128) DEFAULT NULL,
    avatar_url VARCHAR(512) DEFAULT NULL,
    department_id BIGINT DEFAULT NULL,
    status TINYINT NOT NULL DEFAULT 1,
    is_super_admin TINYINT NOT NULL DEFAULT 0,
    last_login_at TIMESTAMP DEFAULT NULL,
    last_login_ip VARCHAR(64) DEFAULT NULL,
    password_changed_at TIMESTAMP DEFAULT NULL,
    remark VARCHAR(500) DEFAULT NULL,
    created_by BIGINT DEFAULT NULL,
    updated_by BIGINT DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (username),
    UNIQUE (mobile),
    UNIQUE (email),
    INDEX idx_admin_status (status)
);

CREATE TABLE IF NOT EXISTS promotion_user (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_no CHAR(12) NOT NULL,
