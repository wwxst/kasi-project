CREATE TABLE IF NOT EXISTS promotion_order (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    connection_id BIGINT NOT NULL,
    provider_id BIGINT NOT NULL,
    external_order_id VARCHAR(128) NOT NULL,
    external_user_id VARCHAR(128),
    external_drama_id VARCHAR(128),
    search_code VARCHAR(64),
    channel_code VARCHAR(128),
    partner_id VARCHAR(128),
    order_amount_minor BIGINT NOT NULL,
    order_amount DECIMAL(18, 2) NOT NULL,
    currency VARCHAR(16) NOT NULL,
    raw_status VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status REGEXP '^(UNPAID|PAID|REFUNDED|UNKNOWN)$'),
    paid_at TIMESTAMP,
    provider_updated_at TIMESTAMP,
    custom_params VARCHAR(255),
    tracking_no VARCHAR(64),
    promotion_link_id BIGINT,
    user_id BIGINT,
    drama_id BIGINT,
    attribution_status VARCHAR(16) NOT NULL DEFAULT 'UNATTRIBUTED',
    rule_history_id BIGINT,
    channel_fee_rate DECIMAL(12, 10),
    principal_fee_rate DECIMAL(12, 10),
    principal_commission_rate DECIMAL(12, 10),
    downstream_fee_rate DECIMAL(12, 10),
    downstream_commission_rate DECIMAL(12, 10),
    commission_amount DECIMAL(18, 2),
    commission_status VARCHAR(24),
    raw_payload_json CLOB NOT NULL,
    sync_start_date TIMESTAMP NOT NULL,
    sync_end_date TIMESTAMP NOT NULL,
    last_synced_at TIMESTAMP NOT NULL,
    last_error_message VARCHAR(512),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (connection_id, external_order_id),
    INDEX idx_promotion_order_user_paid (user_id, paid_at),
    INDEX idx_promotion_order_attribution (attribution_status, paid_at));

