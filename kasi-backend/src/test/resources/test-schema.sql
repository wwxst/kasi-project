CREATE TABLE IF NOT EXISTS system_sms_config (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    access_key_id_ciphertext VARCHAR(1024) NOT NULL,
    access_key_secret_ciphertext VARCHAR(1024) NOT NULL,
    sign_name VARCHAR(64) NOT NULL,
    register_template_code VARCHAR(64) NOT NULL,
    login_template_code VARCHAR(64) NOT NULL,
    reset_password_template_code VARCHAR(64) NOT NULL,
    smtp_host VARCHAR(255), smtp_port INT, smtp_username VARCHAR(255),
    smtp_password_ciphertext VARCHAR(1024), smtp_from_address VARCHAR(255),
    email_enabled TINYINT NOT NULL DEFAULT 0,
    enabled TINYINT NOT NULL DEFAULT 0 CHECK (enabled >= 0 AND enabled <= 1),
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS promotion_media_account (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    media_type VARCHAR(32) NOT NULL,
    external_account_id VARCHAR(128) NOT NULL,
    account_name VARCHAR(128) DEFAULT NULL,
    account_link VARCHAR(512) DEFAULT NULL,
    status TINYINT NOT NULL DEFAULT 1,
    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (media_type, external_account_id),
    INDEX idx_media_account_user_status (user_id, status));

CREATE TABLE IF NOT EXISTS provider_media_filing (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    connection_id BIGINT NOT NULL,
    media_account_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    submitted_data_version INT DEFAULT NULL,
    task_data_version INT NOT NULL DEFAULT 1,
    remote_status VARCHAR(64) DEFAULT NULL,
    external_filing_id VARCHAR(128) DEFAULT NULL,
    filing_time TIMESTAMP DEFAULT NULL,
    operate_time TIMESTAMP DEFAULT NULL,
    operate_by BIGINT DEFAULT NULL,
    next_action VARCHAR(16) NOT NULL DEFAULT 'SUBMIT',
    next_action_at TIMESTAMP DEFAULT NULL,
    retry_count INT NOT NULL DEFAULT 0,
    last_submitted_at TIMESTAMP DEFAULT NULL,
    last_queried_at TIMESTAMP DEFAULT NULL,
    last_error_code VARCHAR(64) DEFAULT NULL,
    last_error_message VARCHAR(512) DEFAULT NULL,
    lease_owner VARCHAR(64) DEFAULT NULL,
    lease_until TIMESTAMP DEFAULT NULL,
    UNIQUE (connection_id, media_account_id),
    INDEX idx_filing_due_task (next_action, next_action_at),
    INDEX idx_filing_media_account (media_account_id));

CREATE TABLE IF NOT EXISTS provider_drama (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    connection_id BIGINT NOT NULL,
    external_drama_id VARCHAR(128) NOT NULL,
    title VARCHAR(255) NOT NULL,
    original_title VARCHAR(255),
    title_zh VARCHAR(255),
    description CLOB,
    cover_url VARCHAR(1024),
    label_names CLOB,
    category_name VARCHAR(255),
    language VARCHAR(32) NOT NULL,
      remote_rank INT,
      drama_type VARCHAR(64),
      novel_type VARCHAR(32),
      novel_sub_type INT,
      commission_scope VARCHAR(255),
      promotion_description CLOB,
      remote_show_status VARCHAR(32),
    local_status VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED',
    remote_created_at TIMESTAMP,
    remote_updated_at TIMESTAMP,
    last_seen_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (connection_id, external_drama_id),
    INDEX idx_provider_drama_query (connection_id, language, local_status));

CREATE TABLE IF NOT EXISTS provider_drama_content (
