CREATE TABLE IF NOT EXISTS drama_sync_display_run_item (
    run_id VARCHAR(36) NOT NULL,
    task_domain VARCHAR(16) NOT NULL,
    task_id BIGINT NOT NULL,
    PRIMARY KEY (run_id, task_domain, task_id),
